def _initial_transmissivity(
    k: np.ndarray,
    initial_head: np.ndarray,
    top: np.ndarray,
    bottom: np.ndarray,
    active: np.ndarray,
    min_sat: float = DEFAULT_MIN_SAT,
) -> np.ndarray:
    thickness = np.maximum(
        np.asarray(initial_head, dtype=np.float64) - np.asarray(bottom, dtype=np.float64),
        float(min_sat),
    )
    full_thickness = np.maximum(
        np.asarray(top, dtype=np.float64) - np.asarray(bottom, dtype=np.float64),
        float(min_sat),
    )
    t = np.asarray(k, dtype=np.float64) * np.minimum(thickness, full_thickness)
    t[np.asarray(active, dtype=np.int32) == 0] = 0.0
    return t.astype(np.float64, copy=False)


def _confined_transmissivity(
    k: np.ndarray,
    top: np.ndarray,
    bottom: np.ndarray,
    active: np.ndarray,
    min_sat: float = DEFAULT_MIN_SAT,
) -> np.ndarray:
    """
    Build the fixed transmissivity used by MF6 confined single-layer runs.

    With ``icelltype=0`` MF6 uses the full cell thickness, not the current head
    or warm-start head, to define saturated thickness.
    """
    thickness = np.maximum(
        np.asarray(top, dtype=np.float64) - np.asarray(bottom, dtype=np.float64),
        float(min_sat),
    )
    transmissivity = np.asarray(k, dtype=np.float64) * thickness
    transmissivity[np.asarray(active, dtype=np.int32) == 0] = 0.0
    return transmissivity.astype(np.float64, copy=False)


def _confined_storage_coeff(
    ss: float,
    top: np.ndarray,
    bottom: np.ndarray,
    active: np.ndarray,
    min_sat: float = DEFAULT_MIN_SAT,
) -> np.ndarray:
    """
    Convert specific storage to MF6-equivalent confined storativity.
    """
    thickness = np.maximum(
        np.asarray(top, dtype=np.float64) - np.asarray(bottom, dtype=np.float64),
        float(min_sat),
    )
    storage = float(ss) * thickness
    storage[np.asarray(active, dtype=np.int32) == 0] = 0.0
    return storage.astype(np.float64, copy=False)


def build_unconfined_storativity(
    *,
    sy: float,
    active: np.ndarray,
    bc_mask: np.ndarray,
    ss: float = 0.0,
    head_ref: np.ndarray | None = None,
    head_old: np.ndarray | None = None,
    bottom: np.ndarray | None = None,
    top: np.ndarray | None = None,
    min_sat: float = DEFAULT_MIN_SAT,
    include_specific_storage: bool = False,
    storage_mode: str | None = None,
    storage_top_threshold: str = STORAGE_TOP_THRESHOLD_GE,
    secant_eps: float = 1.0e-12,
) -> tuple[np.ndarray, np.ndarray | None]:
    """
    Build a dimensionless storativity field for 2D unconfined transient replay.

    Warp's transient term is ``storage_coeff * dx**2 / dt`` per active
    non-boundary cell, so ``storage_coeff`` MUST be a storativity ``S``
    (dimensionless) - not an ambiguous MF6 parameter. Specific yield ``Sy`` is
    already a storativity component; specific storage ``Ss`` (units 1/length) is
    NOT and must be converted to a storativity by multiplying by saturated
    thickness.

    * ``include_specific_storage=False`` / ``phreatic_only``:
        ``S = Sy`` on active non-boundary water-table cells.
    * ``integrated_sy_ss`` / legacy ``mf6_convertible``:
        Simple vertically integrated unconfined approximation.
        ``S = Sy + Ss * saturated_thickness_ref`` where
        ``saturated_thickness_ref = clip(head_ref - bottom, min_sat, top-bottom)``.
        This is the existing vertically integrated approximation and applies
        ``Sy`` even where the reference head is at or above ``top``.
    * ``mf6_convertible_top_switch``:
        MF6-compatible benchmark mode.
        ``S = Ss * full_thickness`` where the selected top-threshold rule is
        met, otherwise ``S = Sy + Ss * saturated_thickness_ref``.
        The closest tested MF6 match uses ``storage_reference=current_picard``
        with threshold ``ge``.
    * ``mf6_convertible_secant_sy``:
        Diagnostic crossing-aware approximation. ``Sy`` is converted to a
        secant coefficient from the change in clipped saturated length between
        ``head_old`` and ``head_ref``.

    Inactive and fixed-head boundary cells are zeroed: they carry no storage in
    the Warp 5-point transient assembly (the solver zeroes them too, so this is
    defensive and keeps the field self-describing).

    Returns ``(storativity, saturated_thickness_reference)`` where the second
    element is the saturated-thickness field used for the ``Ss`` term (or
    ``None`` when ``include_specific_storage`` is False).
    """
    mode = (
        UNCONFINED_STORAGE_MF6_CONVERTIBLE
        if storage_mode is None and include_specific_storage
        else (
            UNCONFINED_STORAGE_PHREATIC_ONLY
            if storage_mode is None
            else str(storage_mode).strip().lower()
        )
    )
    if mode not in UNCONFINED_STORAGE_MODES:
        raise ValueError(f"storage_mode must be one of {sorted(UNCONFINED_STORAGE_MODES)}.")
    threshold_mode = str(storage_top_threshold).strip().lower()
    if threshold_mode not in STORAGE_TOP_THRESHOLD_MODES:
        raise ValueError(f"storage_top_threshold must be one of {sorted(STORAGE_TOP_THRESHOLD_MODES)}.")

    active_i = np.asarray(active, dtype=np.int32)
    bcm = np.asarray(bc_mask, dtype=np.int32)
    shape = active_i.shape
    free = (active_i != 0) & (bcm == 0)
    components = compute_unconfined_storage_components(
        sy=float(sy),
        ss=float(ss),
        head_ref=head_ref,
        head_old=head_old,
        bottom=bottom,
        top=top,
        active=active_i,
        bc_mask=bcm,
        min_sat=float(min_sat),
        storage_mode=mode,
        storage_top_threshold=threshold_mode,
        secant_eps=float(secant_eps),
    )
    storativity = np.asarray(components["storage_coeff"], dtype=np.float64)
    sat_ref = np.asarray(components["sat_ref_ss"], dtype=np.float64) if components["sat_ref_ss"] is not None else None

    return (
        storativity.astype(np.float64, copy=False),
        None if sat_ref is None else sat_ref.astype(np.float64, copy=False),
    )


def compute_unconfined_storage_components(
    *,
    sy: float,
    ss: float,
    head_ref: np.ndarray | None,
    head_old: np.ndarray | None,
    bottom: np.ndarray | None,
    top: np.ndarray | None,
    active: np.ndarray,
    bc_mask: np.ndarray,
    min_sat: float,
    storage_mode: str,
    storage_top_threshold: str = STORAGE_TOP_THRESHOLD_GE,
    secant_eps: float = 1.0e-12,
    above_top_mask_override: np.ndarray | None = None,
) -> dict[str, np.ndarray | None]:
    """
    Compute storage coefficients and component fields for 2D unconfined replay.

    :param sy: Specific yield.
    :param ss: Specific storage.
    :param head_ref: Reference head used for storage.
    :param head_old: Previous-time head used for secant/crossing diagnostics.
    :param bottom: Model bottom.
    :param top: Model top.
    :param active: Active mask.
    :param bc_mask: Dirichlet mask.
    :param min_sat: Minimum saturated thickness used for elastic storage.
    :param storage_mode: Unconfined storage mode.
    :param storage_top_threshold: ``ge`` or ``gt`` for top-switch mode.
    :param secant_eps: Small denominator safeguard for secant mode.
    :param above_top_mask_override: Optional override of the effective above-top mask.
    :return: Dictionary with total, Sy, and Ss coefficients plus saturation helpers.
    """
    mode = str(storage_mode).strip().lower()
    threshold_mode = str(storage_top_threshold).strip().lower()
    if mode not in UNCONFINED_STORAGE_MODES:
        raise ValueError(f"storage_mode must be one of {sorted(UNCONFINED_STORAGE_MODES)}.")
    if threshold_mode not in STORAGE_TOP_THRESHOLD_MODES:
        raise ValueError(f"storage_top_threshold must be one of {sorted(STORAGE_TOP_THRESHOLD_MODES)}.")

    active_i = np.asarray(active, dtype=np.int32)
    bc_i = np.asarray(bc_mask, dtype=np.int32)
    free = (active_i != 0) & (bc_i == 0)
    shape = active_i.shape

    storage_coeff = np.zeros(shape, dtype=np.float64)
    sy_coeff = np.zeros(shape, dtype=np.float64)
    ss_coeff = np.zeros(shape, dtype=np.float64)
    sat_old_zero = np.zeros(shape, dtype=np.float64)
    sat_ref_zero = np.zeros(shape, dtype=np.float64)
    sat_ref_ss = np.zeros(shape, dtype=np.float64)
    full_thickness = None
    raw_above_top = None
    effective_above_top = None

    if mode == UNCONFINED_STORAGE_PHREATIC_ONLY:
        sy_coeff[free] = float(sy)
        storage_coeff[free] = float(sy)
        return {
            "storage_coeff": storage_coeff,
            "sy_coeff": sy_coeff,
            "ss_coeff": ss_coeff,
            "sat_old_zero": sat_old_zero,
            "sat_ref_zero": sat_ref_zero,
            "sat_ref_ss": None,
            "full_thickness": None,
            "raw_above_top": None,
            "effective_above_top": None,
        }

    if head_ref is None or bottom is None or top is None:
        raise ValueError(f"storage_mode='{mode}' requires head_ref, bottom, and top.")

    head_ref_arr = np.asarray(head_ref, dtype=np.float64)
    bottom_arr = np.asarray(bottom, dtype=np.float64)
    top_arr = np.asarray(top, dtype=np.float64)
    full_thickness = np.maximum(top_arr - bottom_arr, float(min_sat))
    sat_ref_zero = np.clip(head_ref_arr - bottom_arr, 0.0, full_thickness)
    sat_ref_ss = np.clip(head_ref_arr - bottom_arr, float(min_sat), full_thickness)

    if head_old is None:
        head_old_arr = head_ref_arr
    else:
        head_old_arr = np.asarray(head_old, dtype=np.float64)
    sat_old_zero = np.clip(head_old_arr - bottom_arr, 0.0, full_thickness)

    if mode in {UNCONFINED_STORAGE_INTEGRATED_SY_SS, UNCONFINED_STORAGE_MF6_CONVERTIBLE}:
        sy_coeff[free] = float(sy)
        ss_coeff[free] = float(ss) * sat_ref_ss[free]
    elif mode == UNCONFINED_STORAGE_MF6_CONVERTIBLE_TOP_SWITCH:
        raw_above_top = top_switch_above_mask(
            head_ref=head_ref_arr,
            top=top_arr,
            threshold_mode=threshold_mode,
            active=active_i,
            bc_mask=bc_i,
        )
        effective_above_top = (
            np.asarray(above_top_mask_override, dtype=bool)
            if above_top_mask_override is not None
            else raw_above_top.copy()
        )
        effective_above_top = effective_above_top & free
        sy_coeff[free] = float(sy)
        sy_coeff[effective_above_top] = 0.0
        ss_coeff[free] = float(ss) * sat_ref_ss[free]
        ss_coeff[effective_above_top] = float(ss) * full_thickness[effective_above_top]
    elif mode == UNCONFINED_STORAGE_MF6_CONVERTIBLE_SECANT_SY:
        dh_ref = head_ref_arr - head_old_arr
        sy_coeff_calc = np.zeros(shape, dtype=np.float64)
        moving = np.abs(dh_ref) > float(secant_eps)
        sy_coeff_calc[moving] = float(sy) * (
            (sat_ref_zero[moving] - sat_old_zero[moving]) / dh_ref[moving]
        )
        fallback_below_top = (np.abs(dh_ref) <= float(secant_eps)) & (head_ref_arr < top_arr) & (head_ref_arr > bottom_arr)
        sy_coeff_calc[fallback_below_top] = float(sy)
        sy_coeff_calc = np.clip(sy_coeff_calc, 0.0, float(sy))
        sy_coeff[free] = sy_coeff_calc[free]
        ss_coeff[free] = float(ss) * sat_ref_ss[free]
    elif mode == UNCONFINED_STORAGE_MF6_CONVERTIBLE_CROSSING_VOLUME_SY:
        dh_ref = head_ref_arr - head_old_arr
        sy_coeff_calc = np.zeros(shape, dtype=np.float64)
        moving = np.abs(dh_ref) > float(secant_eps)
        sy_coeff_calc[moving] = float(sy) * (
            (sat_ref_zero[moving] - sat_old_zero[moving]) / dh_ref[moving]
        )
        fallback_below_top = (np.abs(dh_ref) <= float(secant_eps)) & (head_ref_arr < top_arr) & (head_ref_arr > bottom_arr)
        sy_coeff_calc[fallback_below_top] = float(sy)
        sy_coeff_calc = np.clip(sy_coeff_calc, 0.0, float(sy))
        sy_coeff[free] = sy_coeff_calc[free]
        ss_coeff[free] = float(ss) * sat_ref_ss[free]
    else:
        raise ValueError(f"unsupported storage_mode '{mode}'.")

    storage_coeff = sy_coeff + ss_coeff
    storage_coeff[~free] = 0.0
    sy_coeff[~free] = 0.0
    ss_coeff[~free] = 0.0
    sat_old_zero[~free] = 0.0
    sat_ref_zero[~free] = 0.0
    sat_ref_ss[~free] = 0.0

    return {
        "storage_coeff": storage_coeff,
        "sy_coeff": sy_coeff,
        "ss_coeff": ss_coeff,
        "sat_old_zero": sat_old_zero,
        "sat_ref_zero": sat_ref_zero,
        "sat_ref_ss": sat_ref_ss,
        "full_thickness": full_thickness,
        "raw_above_top": raw_above_top,
        "effective_above_top": effective_above_top,
    }


def top_switch_above_mask(
    *,
    head_ref: np.ndarray,
    top: np.ndarray,
    threshold_mode: str = STORAGE_TOP_THRESHOLD_GE,
    active: np.ndarray | None = None,
    bc_mask: np.ndarray | None = None,
) -> np.ndarray:
    """
    Build the raw above-top mask for MF6-like unconfined top-switch storage.

    :param head_ref: Reference head field.
    :param top: Model-top elevation field.
    :param threshold_mode: ``ge`` or ``gt``.
    :param active: Optional active mask.
    :param bc_mask: Optional Dirichlet mask.
    :return: Boolean above-top mask.
    """
    head_ref_arr = np.asarray(head_ref, dtype=np.float64)
    top_arr = np.asarray(top, dtype=np.float64)
    mode = str(threshold_mode).strip().lower()
    if mode == STORAGE_TOP_THRESHOLD_GE:
        above = head_ref_arr >= top_arr
    elif mode == STORAGE_TOP_THRESHOLD_GT:
        above = head_ref_arr > top_arr
    else:
        raise ValueError(f"threshold_mode must be one of {sorted(STORAGE_TOP_THRESHOLD_MODES)}.")
    if active is not None:
        above = above & (np.asarray(active, dtype=np.int32) != 0)
    if bc_mask is not None:
        above = above & (np.asarray(bc_mask, dtype=np.int32) == 0)
    return above


def apply_top_switch_hysteresis(
    *,
    raw_above_top: np.ndarray,
    head_ref: np.ndarray,
    top: np.ndarray,
    previous_above_top: np.ndarray | None,
    hysteresis_eps: float,
    active: np.ndarray | None = None,
    bc_mask: np.ndarray | None = None,
) -> np.ndarray:
    """
    Apply a symmetric top hysteresis band to a raw top-switch mask.

    :param raw_above_top: Raw above-top mask for the current head.
    :param head_ref: Current reference head field.
    :param top: Model-top elevation field.
    :param previous_above_top: Previous effective above-top mask.
    :param hysteresis_eps: Symmetric hysteresis half-band around ``top``.
    :param active: Optional active mask.
    :param bc_mask: Optional Dirichlet mask.
    :return: Stabilised above-top mask.
    """
    raw_mask = np.asarray(raw_above_top, dtype=bool)
    if previous_above_top is None:
        out = raw_mask.copy()
    else:
        head_ref_arr = np.asarray(head_ref, dtype=np.float64)
        top_arr = np.asarray(top, dtype=np.float64)
        prev_mask = np.asarray(previous_above_top, dtype=bool)
        eps = max(float(hysteresis_eps), 0.0)
        out = raw_mask.copy()
        out[prev_mask & (head_ref_arr >= (top_arr - eps))] = True
        out[(~prev_mask) & (head_ref_arr < (top_arr + eps))] = False
    if active is not None:
        out = out & (np.asarray(active, dtype=np.int32) != 0)
    if bc_mask is not None:
        out = out & (np.asarray(bc_mask, dtype=np.int32) == 0)
    return out


def should_freeze_top_switch(
    *,
    changed_fraction: float,
    stable_iteration_count: int,
    fraction_tol: float,
    freeze_after_stable_iterations: int,
) -> bool:
    """
    Decide whether the top-switch active set should be frozen.

    :param changed_fraction: Fraction of free cells whose top-switch state changed.
    :param stable_iteration_count: Consecutive stable-iteration counter.
    :param fraction_tol: Fraction threshold treated as stable.
    :param freeze_after_stable_iterations: Required stable-iteration count.
    :return: True when the mask should freeze.
    """
    if int(freeze_after_stable_iterations) <= 0:
        return False
    return (
        float(changed_fraction) <= float(fraction_tol)
        and int(stable_iteration_count) >= int(freeze_after_stable_iterations)
    )


def validate_warm_start_head(
    head: np.ndarray,
    spatial: dict,
    label: str = "warm_start_head",
) -> np.ndarray:
    """
    Validate and normalize a warm-start head against replay spatial fields.
    """
    h = np.asarray(head, dtype=np.float64).copy()
    shape = (int(spatial["ny"]), int(spatial["nx"]))
    if h.shape != shape:
        raise ValueError(f"{label} shape {h.shape} expected {shape}.")
    if not np.all(np.isfinite(h)):
        raise ValueError(f"{label} contains non-finite values.")

    active = np.asarray(spatial["active"], dtype=np.int32)
    bc_mask = np.asarray(spatial["bc_mask"], dtype=np.int32)
    bc_values = np.asarray(spatial["bc_values"], dtype=np.float64)
    bottom = np.asarray(spatial["bottom"], dtype=np.float64)
    top = np.asarray(spatial["top"], dtype=np.float64)

    h[active == 0] = 0.0
    h[bc_mask != 0] = bc_values[bc_mask != 0]

    free = (active != 0) & (bc_mask == 0)
    if np.any(free):
        min_allowed = bottom[free] - 1.0e-6
        max_allowed = top[free] + max(100.0, 0.1 * float(np.nanmax(top[free] - bottom[free])))
        if np.any(h[free] < min_allowed):
            raise ValueError(f"{label} has active free-cell heads below cell bottom.")
        if np.any(h[free] > max_allowed):
            raise ValueError(f"{label} has implausibly high active free-cell heads.")
    return h.astype(np.float64, copy=False)


def select_artifact_warm_start(
    artifact: dict,
    spatial: dict,
    warm_start_mode: str,
) -> tuple[np.ndarray, str]:
    """
    Select an artifact-backed warm start for replay.
    """
    mode = str(warm_start_mode).strip().lower()
    if mode not in WARM_START_ARTIFACT_MODES:
        raise ValueError(
            f"artifact warm_start_mode must be one of {sorted(WARM_START_ARTIFACT_MODES)}."
        )
    if mode == WARM_START_ARTIFACT_INITIAL:
        return validate_warm_start_head(
            head=artifact["initial_head"],
            spatial=spatial,
            label="artifact initial_head",
        ), WARM_START_ARTIFACT_INITIAL

    if mode == WARM_START_CONFINED_STEADY_MF6:
        if "confined_steady_head" not in artifact:
            raise KeyError(
                "warm_start_mode='confined_steady_mf6' requires artifact key "
                "'confined_steady_head'. Regenerate the artifact with "
                "working_tests/run_2d_transient_vs_mf6.py."
            )
        return validate_warm_start_head(
            head=artifact["confined_steady_head"],
            spatial=spatial,
            label="artifact confined_steady_head",
        ), WARM_START_CONFINED_STEADY_MF6

    if "unconfined_steady_head" not in artifact:
        raise KeyError(
            "warm_start_mode='unconfined_steady_mf6' requires artifact key "
            "'unconfined_steady_head'. Regenerate the artifact with "
            "working_tests/run_2d_transient_vs_mf6.py."
        )
    return validate_warm_start_head(
        head=artifact["unconfined_steady_head"],
        spatial=spatial,
        label="artifact unconfined_steady_head",
    ), WARM_START_UNCONFINED_STEADY_MF6


def artifact_warm_start_provenance(artifact: dict) -> str | None:
    """
    Return the ``warm_start_mode`` recorded in the artifact provenance, if any.

    The MF6 truth generator records which warm start produced the artifact's
    ``initial_head``. This is used to check that a Warp replay warm start is
    comparable to the MF6 truth.
    Returns ``None`` for artifacts without parseable warm-start provenance.
    """
    provenance = artifact.get("provenance")
    if provenance is None:
        return None
    try:
        data = json.loads(_scalar_string(provenance))
    except (TypeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(data, dict):
        return None
    mode = str(data.get("warm_start_mode", "")).strip().lower()
    return mode or None


def validate_warm_start_comparability(
    artifact_warm_start: str | None,
    warp_warm_start_mode: str,
    allow_warm_start_mismatch: bool = False,
) -> None:
    """
    Ensure a Warp replay warm start is comparable to the MF6 artifact provenance.

    A replay must use the artifact's own transient initial condition or the same
    recorded warm-start mode. Re-solving a warm start with Warp, or selecting a
    different artifact-backed steady head, is not comparable to MF6 heads that
    started from another state. That mismatch conflates warm-start error with
    transient error and must be opted into explicitly.

    Raises ``ValueError`` on a mismatch unless ``allow_warm_start_mismatch`` is
    True. Artifacts without warm-start provenance are allowed through silently,
    and ``artifact_initial`` is always comparable because it uses the artifact's
    stored transient initial head directly.
    """
    if artifact_warm_start is None:
        return
    if warp_warm_start_mode == WARM_START_ARTIFACT_INITIAL:
        return
    if artifact_warm_start == warp_warm_start_mode:
        return
    if allow_warm_start_mismatch:
        return
    raise ValueError(
        f"Warp warm_start_mode='{warp_warm_start_mode}' does not match the MF6 "
        f"artifact warm-start provenance '{artifact_warm_start}'. That makes the "
        f"Warp-vs-MF6 head comparison invalid (warm-start error is conflated with "
        f"transient error). Use warm_start_mode='{artifact_warm_start}' or "
        f"'artifact_initial' to start from the artifact's own initial head, or pass "
        f"allow_warm_start_mismatch=True to proceed anyway."
    )


def representative_recharge_rate(recharge_rates: np.ndarray) -> float:
    rates = np.asarray(recharge_rates, dtype=np.float64).reshape(-1)
    if rates.size == 0:
        raise ValueError("recharge_rates must contain at least one value.")
    if not np.all(np.isfinite(rates)):
        raise ValueError("recharge_rates must be finite.")
    return float(np.mean(rates))


